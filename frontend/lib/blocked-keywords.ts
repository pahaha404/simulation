export function hasBlockedKeyword(text: string) {
  const normalized = text.trim().toLowerCase().replace(/\s+/g, "")
  return (
    blockedKeywords.some((keyword) => normalized.includes(keyword.toLowerCase().replace(/\s+/g, ""))) ||
    lowEffortPatterns.some((pattern) => pattern.test(normalized)) ||
    normalized.length <= 1
  )
}
